"""Regression: a Piano Roll save survives the .s being rewritten underneath it.

THE BUG (reported 2026-11-18). An instrument was changed from banjo to nylon
string guitar in the Piano Roll. Save gave:

    'mus_faron_woods' was NOT saved -- nothing on disk was changed.
    mus_faron_woods_1 no longer matches its file -- the song was changed on
    disk after it was opened here. Reopen it and make the edit again.

Nothing about the music had changed. `TrackCommand.origin` -- the thing the
save matches an editor's commands against the file by -- was
`(line number, position on the line)`, so a command's identity depended on
WHERE IN THE FILE it sat. Two ordinary things move those lines:

* a build, which regenerates the .s from the .mid;
* Song Build Protection, which adds one `@ song-guard v1 ...` line at the top
  of every .s and so pushes the whole file down by one line.

Either one invalidated every origin an open editor was holding, and every
later save was refused.

THE RULE: `origin` is `(track index, ordinal among that track's VALUE
commands)` -- it says WHICH COMMAND THIS IS, never where it sits. Notes and
structure are excluded, so adding a note in the editor cannot renumber the
commands after it. The refusal must STAY for a file whose music really did
change: that is the only thing standing between a rewritten file and wrong
values being written into somebody's song.
"""
import os
import sys

import pytest

ROOT_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
for _p in (ROOT_DIR, os.path.join(ROOT_DIR, 'core')):
    if _p not in sys.path:
        sys.path.insert(0, _p)

from core.sound.song_parser import (          # noqa: E402
    parse_song_file, is_value_command, STRUCTURE_CMDS, NOTE_CMDS,
)
from core.sound.safe_song_save import (       # noqa: E402
    apply_command_edits, SongSaveRefused,
)

SONG = """\t.include "MPlayDef.s"

\t.equ\tmus_test_grp, voicegroup013
\t.equ\tmus_test_mvl, 127
\t.equ\tmus_test_key, 0
\t.equ\tmus_test_tbs, 1

\t.section .rodata
\t.global\tmus_test
\t.align\t2

@********************** Track 1 **********************@

mus_test_1:
\t.byte\tKEYSH , mus_test_key+0
@ 000   ----------------------------------------
\t.byte\tTEMPO , 96*mus_test_tbs/2
\t.byte\t\tVOICE , 24
\t.byte\t\tVOL   , 99*mus_test_mvl/mxv
\t.byte\t\tN24   , Ds4 , v100
\t.byte\tW24
\t.byte\t\tPAN   , c_v+10
\t.byte\t\tN24   , Fn4 , v100
\t.byte\tW24
\t.byte\tFINE

@******************************************************@
\t.align\t2
"""

# The SAME music after a rebuild: Song Build Protection's header line on top,
# the comment banner re-flowed. Every line has moved; not a note has changed.
REBUILT = ('@ song-guard v1 mid=abc123 s=def456 flags: -E -G013 -R50 -V100\n'
           + SONG.replace(
               '@ 000   ----------------------------------------',
               '@ 000   ----------------------------------------\n'
               '@ regenerated by mid2agb'))


def _write(tmp_path, name, text):
    p = tmp_path / name
    p.write_text(text, encoding='utf-8')
    return parse_song_file(str(p))


@pytest.fixture
def songs(tmp_path):
    """The song as the editor holds it, and the same music re-read after a
    rewrite that moved every line."""
    live = _write(tmp_path, 'live.s', SONG)
    base = _write(tmp_path, 'base.s', REBUILT)
    return live.tracks[0], base.tracks[0]


def _by_cmd(track, name):
    return [c for c in track.commands if c.cmd == name]


# ── What an identity has to be ──────────────────────────────────────────────

def test_identity_does_not_depend_on_the_files_layout(songs):
    """The heart of it: same music, every line moved, same identities."""
    live, base = songs
    live_ids = [c.origin for c in live.commands if is_value_command(c.cmd)]
    base_ids = [c.origin for c in base.commands if is_value_command(c.cmd)]
    assert live_ids == base_ids
    assert all(i is not None for i in live_ids)


def test_identity_says_which_command_not_which_line(songs):
    live, _ = songs
    vals = [(c.cmd, c.origin) for c in live.commands if is_value_command(c.cmd)]
    assert [c for c, _ in vals] == ['KEYSH', 'TEMPO', 'VOICE', 'VOL', 'PAN']
    # Numbered straight through, in the order they play -- no gaps for the
    # notes and waits sitting between them in the file.
    assert [o for _, o in vals] == [(0, i) for i in range(5)]


def test_notes_and_structure_carry_no_identity(songs):
    """So adding a note in the editor cannot renumber what follows it."""
    live, _ = songs
    for c in live.commands:
        if c.cmd in NOTE_CMDS or c.cmd in STRUCTURE_CMDS:
            assert c.origin is None, (c.cmd, c.origin)


def test_a_note_does_not_sit_between_two_value_commands_in_the_numbering(songs):
    live, _ = songs
    pan = _by_cmd(live, 'PAN')[0]
    vol = _by_cmd(live, 'VOL')[0]
    # A note and a wait sit between them in the FILE; in the numbering they
    # are adjacent, which is what makes the numbering survive an added note.
    assert pan.origin[1] == vol.origin[1] + 1


# ── The bug the user hit ────────────────────────────────────────────────────

def test_an_instrument_edit_saves_after_the_file_was_rewritten(songs):
    """banjo -> nylon string guitar, against a .s that gained a header line."""
    live, base = songs
    _by_cmd(live, 'VOICE')[0].value = 25
    changed = apply_command_edits(base, live)
    assert 'VOICE' in changed
    assert _by_cmd(base, 'VOICE')[0].value == 25


def test_an_untouched_song_reports_no_change(songs):
    live, base = songs
    assert apply_command_edits(base, live) == set()


# ── The refusal that must stay ──────────────────────────────────────────────

def test_a_song_whose_music_really_changed_is_still_refused(tmp_path, songs):
    """Somebody added a command to the file; matching up would be guessing."""
    live, _ = songs
    meddled = _write(tmp_path, 'meddled.s',
                     SONG.replace('\t\t.byte\t\tVOL   , 99*mus_test_mvl/mxv',
                                  '\t.byte\t\tVOL   , 99*mus_test_mvl/mxv')
                     .replace('\t.byte\t\tVOICE , 24',
                              '\t.byte\t\tVOICE , 99'))
    _by_cmd(live, 'PAN')[0].value = 5
    with pytest.raises(SongSaveRefused):
        apply_command_edits(meddled.tracks[0], live)


def test_the_refusal_says_to_reopen(tmp_path, songs):
    live, _ = songs
    meddled = _write(tmp_path, 'meddled2.s',
                     SONG.replace('VOICE , 24', 'VOICE , 99'))
    with pytest.raises(SongSaveRefused) as exc:
        apply_command_edits(meddled.tracks[0], live)
    assert 'Reopen it' in str(exc.value)


# ── Edits other than a value change still work ──────────────────────────────

def test_a_command_the_editor_created_is_still_inserted(songs):
    live, base = songs
    import copy
    made = copy.copy(_by_cmd(live, 'PAN')[0])
    made.origin = None            # the editor created it
    made.value = 42
    live.commands.insert(live.commands.index(_by_cmd(live, 'PAN')[0]), made)
    apply_command_edits(base, live)
    # c_v+10 parses to 74; the created one keeps the 42 it was given.
    assert [c.value for c in _by_cmd(base, 'PAN')] == [42, 74]


def test_a_command_the_editor_removed_is_still_removed(songs):
    live, base = songs
    live.commands.remove(_by_cmd(live, 'PAN')[0])
    changed = apply_command_edits(base, live)
    assert _by_cmd(base, 'PAN') == []
    assert 'PAN' in changed


def test_adding_a_note_does_not_disturb_the_value_commands(songs):
    """The reason notes are left out of the numbering."""
    live, base = songs
    import copy
    note = copy.copy(_by_cmd(live, 'NOTE')[0] if _by_cmd(live, 'NOTE')
                     else live.commands[0])
    live.commands.insert(0, note)
    _by_cmd(live, 'VOL')[0].value = 70
    apply_command_edits(base, live)
    assert _by_cmd(base, 'VOL')[0].value == 70
